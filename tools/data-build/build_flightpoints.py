# Builds addon/LevelingLedger/FlightData.lua: every WoW Forever flight master, for the add-on's flight point map pins.
#   python3 -I build_flightpoints.py <QuestieDB checkout>
# From QuestieDB's Forever NPC data (data/Forever/foreverNpcDB.lua, GPL-3.0 like this project; read as data, nothing
# is run): NPCs with the flight master flag (npcFlags & 8), their title, which faction they serve, and where they stand
# (Questie area id, converted to the game's zone map with support/Forever/Zones/areaIdToUiMapId.lua for /way lines).
# Zone names: the game's zone maps; areas outside them are named from QuestieDB's zone list.
import sys, os, re
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from luaparse import parse_data_string
Q = sys.argv[1]
OUT = os.path.join(HERE, '..', '..', 'addon', 'LevelingLedger', 'FlightData.lua')
FLIGHT_MASTER = 8  # mangos-classic UNIT_NPC_FLAG_FLIGHTMASTER

npcs = parse_data_string(open(os.path.join(Q, 'data', 'Forever', 'foreverNpcDB.lua'), encoding='utf-8').read(), 'QuestieDB.npcData')
amap = {}
for a, u in re.findall(r'\[(\d+)\]\s*=\s*(\d+)', open(os.path.join(Q, 'support', 'Forever', 'Zones', 'areaIdToUiMapId.lua'), encoding='utf-8').read()):
    amap.setdefault(int(a), int(u))
UIMAP = dict(zip(range(1411, 1459), ["Durotar", "Mulgore", "The Barrens", "Kalimdor", "Eastern Kingdoms", "Alterac Mountains", "Arathi Highlands",
  "Badlands", "Blasted Lands", "Tirisfal Glades", "Silverpine Forest", "Western Plaguelands", "Eastern Plaguelands", "Hillsbrad Foothills",
  "The Hinterlands", "Dun Morogh", "Searing Gorge", "Burning Steppes", "Elwynn Forest", "Deadwind Pass", "Duskwood", "Loch Modan",
  "Redridge Mountains", "Stranglethorn Vale", "Swamp of Sorrows", "Westfall", "Wetlands", "Teldrassil", "Darkshore", "Ashenvale",
  "Thousand Needles", "Stonetalon Mountains", "Desolace", "Feralas", "Dustwallow Marsh", "Tanaris", "Azshara", "Felwood", "Un'Goro Crater",
  "Moonglade", "Silithus", "Winterspring", "Stormwind City", "Orgrimmar", "Ironforge", "Thunder Bluff", "Darnassus", "Undercity"]))
ZN = {}
for k, v in re.findall(r'^\s*([A-Z0-9_]+)\s*=\s*(\d+)\s*,', open(os.path.join(Q, 'src', 'corrections', 'enum', 'zones.lua'), encoding='utf-8').read(), re.M):
    ZN.setdefault(int(v), k.replace('_', ' ').title().replace("'S ", "'s "))
FIX = {'Shen Dar Village': "Shen'dar Village", 'Shen Dralas': "Shen'dralas", 'Shen Dar Highlands': "Shen'dar Highlands"}
def zone(area, m): return UIMAP.get(m) or FIX.get(ZN.get(area, ''), ZN.get(area, '')) or ''

rows, skipped = [], []
for i, n in sorted(npcs.items()):
    if not ((n[14] or 0) & FLIGHT_MASTER) or not n[6]: continue
    fac = n[12] or ''
    if not fac: skipped.append(n[0]); continue  # hostile to both factions
    for area, pts in n[6].items():
        m = amap.get(area)
        if not m: skipped.append(f'{n[0]} (area {area})'); continue
        for x, y in pts[:1]:  # flight masters stand still: their first spawn
            rows.append({'id': i, 'n': n[0], 's': n[13] or 'Flight Master', 'f': 'N' if fac == 'AH' else fac, 'area': area, 'map': m, 'x': x, 'y': y, 'z': zone(area, m)})

def lua_str(s): return '"' + ''.join(c if 32 <= ord(c) < 127 and c not in '"\\' else ''.join('\\%03d' % b for b in c.encode('utf-8')) for c in s) + '"'
lines = ['-- Generated by tools/data-build/build_flightpoints.py: flight masters for the flight point pins (Flights.lua).',
         "-- From QuestieDB's WoW Forever NPC data (GPL-3.0). f: A (Alliance), H (Horde), N (both).",
         'local ADDON, ns = ...', 'ns.flights = {']
for r in sorted(rows, key=lambda r: (r['f'], r['z'], r['n'])):
    lines.append('  { id = %d, n = %s, s = %s, f = "%s", z = %s, area = %d, map = %d, x = %s, y = %s },' % (
        r['id'], lua_str(r['n']), lua_str(r['s']), r['f'], lua_str(r['z']), r['area'], r['map'], r['x'], r['y']))
lines.append('}')
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
from collections import Counter
print(len(rows), 'flight masters', dict(Counter(r['f'] for r in rows)), '| skipped:', skipped)
