# Builds addon/LevelingLedger/ClassSpellsData.lua: every class's trainable spells by rank and level, for the add-on's
# training list (Training.lua).
#   python3 -I build_classspells.py
# From app/public/abilities-forever.json (Forever's game tables via wago.tools): spell id, name, rank, level. Spells
# known from the start ("auto") are left out. Spells that are talents (their names are in talents-<class>.json) are
# marked t = 1: the add-on lists them only once you know a rank (higher ranks are trained; the first is the talent).
import os, re, json
HERE = os.path.dirname(os.path.abspath(__file__))
PUB = os.path.join(HERE, '..', '..', 'app', 'public')
OUT = os.path.join(HERE, '..', '..', 'addon', 'LevelingLedger', 'ClassSpellsData.lua')

ab = json.load(open(os.path.join(PUB, 'abilities-forever.json'), encoding='utf-8'))['classes']
def lua_str(s): return '"' + ''.join(c if 32 <= ord(c) < 127 and c not in '"\\' else ''.join('\\%03d' % b for b in c.encode('utf-8')) for c in s) + '"'
lines = ['-- Generated by tools/data-build/build_classspells.py from app/public/abilities-forever.json (Forever game tables).',
         '-- ns.classSpells[CLASS] = { { spell id, name, rank (0 = none), level, talent (1/nil) }, ... }, by level',
         'local ADDON, ns = ...', 'ns.classSpells = {']
total = 0
for cls, spells in sorted(ab.items()):
    tfile = os.path.join(PUB, f'talents-{cls.lower()}.json')
    talents = {n['name'] for t in json.load(open(tfile, encoding='utf-8'))['trees'] for n in t['nodes']} if os.path.exists(tfile) else set()
    rows, seen = [], set()
    for e in sorted(spells, key=lambda e: (e.get('lv') or 0, e['n'], e.get('r') or '')):
        if e.get('auto') or not e.get('id') or not e.get('lv') or '(Passive' in e['n']: continue
        m = re.search(r'(\d+)', e.get('r') or '')
        rank = int(m.group(1)) if m else 0
        key = (e['n'], rank, e['lv'])
        if key in seen: continue
        seen.add(key)
        rows.append('{ %d, %s, %d, %d%s }' % (e['id'], lua_str(e['n']), rank, e['lv'], ', 1' if e['n'] in talents else ''))
    total += len(rows)
    lines.append('  %s = {' % cls.upper())
    for i in range(0, len(rows), 4): lines.append('    ' + ', '.join(rows[i:i + 4]) + ',')
    lines.append('  },')
lines.append('}')
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
print(total, 'spells for', len(ab), 'classes;', os.path.getsize(OUT), 'bytes')
