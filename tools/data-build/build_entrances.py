# Builds addon/LevelingLedger/EntranceData.lua: where each WoW Forever dungeon and raid is entered, for the add-on's map pins.
#   python3 -I build_entrances.py <QuestieDB checkout>
# Entrance positions: QuestieDB's Forever zone data (support/Forever/Zones/dungeons.lua, entrances in Forever map
# percentages; areaIdToUiMapId.lua for the zone maps). QuestieDB is GPL-3.0, like this project; only the facts are taken
# (which zone, where), read as text: nothing is run. Names, kinds and level ranges come from our own dungeon lists.
# Entrances that share a spot (Blackrock Mountain, the Ahn'Qiraj gates) become one pin listing every instance there.
# The newest Forever dungeons that QuestieDB doesn't place yet are left to the game's own entrance list at runtime.
import sys, os, re, json
HERE = os.path.dirname(os.path.abspath(__file__))
PUB = os.path.join(HERE, '..', '..', 'app', 'public')
OUT = os.path.join(HERE, '..', '..', 'addon', 'LevelingLedger', 'EntranceData.lua')
Z = os.path.join(sys.argv[1], 'support', 'Forever', 'Zones')

src = open(os.path.join(Z, 'dungeons.lua'), encoding='utf-8').read()
base = src[src.index('local dungeons = {'):]
base = base[:base.index('\n}\n')]  # the Forever table only; the later Wotlk/Cata overrides aren't Forever's
ENTRY = re.compile(r'^\s*\[(\d+)\]\s*=\s*\{"([^"]+)",\s*(?:nil|\{[\d,\s]*\}),\s*\d+,\s*\{(.*)\}\},?\s*(?:--\s*(.*))?$')
POINT = re.compile(r'\{\s*(\d+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*\}')
entries = {}
for line in base.splitlines():
    m = ENTRY.match(line)
    if not m or 'isHorde' in line: continue  # battlegrounds (a spot per faction) aren't dungeons
    aid, name, pts, note = int(m.group(1)), m.group(2), m.group(3), (m.group(4) or '')
    entries[aid] = (name, [(int(a), float(x), float(y)) for a, x, y in POINT.findall(pts)], note)

amap = {}
for a, u in re.findall(r'\[(\d+)\]\s*=\s*(\d+)', open(os.path.join(Z, 'areaIdToUiMapId.lua'), encoding='utf-8').read()):
    amap.setdefault(int(a), int(u))  # the first table is the main one; overrides that hide a zone (0) are skipped below

# our dungeons: name -> kind, level range
ours = {}
for f in ('dungeons-forever.json', 'dungeons-curated-forever.json', 'dungeons-att-forever.json'):
    for d in json.load(open(os.path.join(PUB, f), encoding='utf-8'))['dungeons']:
        ours.setdefault(d['n'], {'k': 'R' if d.get('kind') == 'Raid' else 'D', 'lv': d.get('lv')})
# Dire Maul's wings each have their own door: QuestieDB's wing areas, named by its comments
WINGS = {10022: 'Dire Maul North', 10023: 'Dire Maul West', 10026: 'Dire Maul East'}
SKIP = {2557, 10024, 10025, 10027, 10001}  # the whole of Dire Maul (the wings replace it), duplicate wing areas, an unverified Gauntlet spot

spots, placed = {}, set()
for aid, (name, pts, note) in sorted(entries.items()):
    if aid in SKIP: continue
    label = WINGS.get(aid, name)
    info = ours.get(name)
    if not info: continue
    placed.add(name)
    for a, x, y in pts:
        u = amap.get(a)
        if not u: continue
        key = (a, round(x, 1), round(y, 1))
        spots.setdefault(key, {'area': a, 'map': u, 'x': x, 'y': y, 'list': []})
        if label not in [i['n'] for i in spots[key]['list']]:
            spots[key]['list'].append({'n': label, 'k': info['k'], 'lv': info['lv']})
missing = sorted(set(ours) - placed)

def lua_str(s): return '"' + ''.join(c if 32 <= ord(c) < 127 and c not in '"\\' else '\\%03d' % b for c in s for b in c.encode('utf-8')) + '"'
lines = ['-- Generated by tools/data-build/build_entrances.py: dungeon and raid entrances for the map pins (Entrances.lua).',
         '-- Positions: QuestieDB\'s WoW Forever zone data (GPL-3.0). Names and levels: the Leveling Ledger\'s dungeon lists.',
         '-- Each spot: area (Questie area id), map (the game\'s zone map), x, y, and the instances entered there.',
         'local ADDON, ns = ...', 'ns.entrances = {']
for s in sorted(spots.values(), key=lambda s: (min((i['lv'] or [0])[0] for i in s['list']), s['list'][0]['n'])):
    items = ', '.join('{ n = %s, k = "%s"%s }' % (lua_str(i['n']), i['k'], ', lv = { %d, %d }' % tuple(i['lv']) if i['lv'] else '') for i in s['list'])
    lines.append('  { area = %d, map = %d, x = %s, y = %s, list = { %s } },' % (s['area'], s['map'], s['x'], s['y'], items))
lines.append('}')
lines.append('-- not placed yet: the add-on asks the game where these are, and takes their kind and levels from here')
lines.append('ns.entranceInfo = {')
for n in missing:
    i = ours[n]
    lines.append('  [%s] = { k = "%s"%s },' % (lua_str(n.lower()), i['k'], ', lv = { %d, %d }' % tuple(i['lv']) if i['lv'] else ''))
lines.append('}')
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
print(len(spots), 'spots,', sum(len(s['list']) for s in spots.values()), 'instance entrances; not placed:', missing)
